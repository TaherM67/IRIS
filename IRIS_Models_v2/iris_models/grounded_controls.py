"""Experimental candidate relevance using observable SIEM and GRC context.

Association control/risk IDs and offline scenario labels are never read. A
catalogue-matching policy is returned separately from learned scores because the
supplied synthetic targets were generated by a similar catalogue-linking rule.
"""
from __future__ import annotations

from collections import Counter
import hashlib
import json
from pathlib import Path

import joblib
import numpy as np
import sklearn

from .contracts import NUMERIC

SCHEMA = 'iris-grounded-control-candidates-v1'
PAIR_FEATURES = NUMERIC + [
    'asset_criticality', 'current_likelihood', 'impact',
    'candidate_registered_risk_count', 'candidate_matched_risk_count',
    'candidate_matched_event_fraction', 'candidate_catalogue_exact_technique_count',
    'candidate_catalogue_parent_technique_count', 'candidate_applies_to_asset',
    'observed_technique_count', 'matched_registered_risk_count',
]


def technique_match(left, right):
    """Match exact ATT&CK techniques or a shared parent, as declared by source."""
    return bool(left and right and (left == right or left.split('.')[0] == right.split('.')[0]))


def catalogue_digest(catalogue):
    """Bind the learned artifact to candidate IDs and operational metadata."""
    return hashlib.sha256(json.dumps(catalogue, sort_keys=True).encode()).hexdigest()


def candidate_features(session, alerts, asset, registered_risks, catalogue):
    """Build 120 candidate rows without touching source association fields.

    registered_risks must be the asset's applicable pre-decision records. In the
    supplied historical replay, control-membership history is missing; the caller
    must declare its synthetic-only static-membership assumption separately.
    """
    if not alerts:
        raise ValueError('Observed session events are required')
    if session.get('asset_id') != asset.get('asset_id'):
        raise ValueError('Session context belongs to a different asset')
    declared = session.get('source_event_ids')
    if declared is not None and set(declared) != {a.get('alert_id') for a in alerts}:
        raise ValueError('Telemetry does not match the declared session membership')
    if any(risk['asset_id'] != asset['asset_id'] for risk in registered_risks):
        raise ValueError('Risk context belongs to a different asset')
    # Explicit input allowlist: no associations, target flags or oracle scenarios.
    techniques = [a.get('mitre_technique') for a in alerts if a.get('mitre_technique')]
    all_members, matched_members = Counter(), Counter()
    event_members = Counter()
    matched_risks = set()
    for risk in registered_risks:
        members = set(risk.get('existing_control_ids', [])) | set(risk.get('planned_control_ids', []))
        all_members.update(members)
        matching_events = [a for a in alerts if any(technique_match(a.get('mitre_technique'), t)
                           for t in risk.get('mitre_attack_techniques', []))]
        if matching_events:
            matched_risks.add(risk['risk_id'])
            matched_members.update(members)
    for alert in alerts:
        linked = set()
        for risk in registered_risks:
            if any(technique_match(alert.get('mitre_technique'), t) for t in risk.get('mitre_attack_techniques', [])):
                linked.update(risk.get('existing_control_ids', []))
                linked.update(risk.get('planned_control_ids', []))
        event_members.update(linked)
    labels = sorted(c['control_id'] for c in catalogue)
    if len(set(labels)) != len(labels):
        raise ValueError('Duplicate candidate control ID')
    by_id = {c['control_id']: c for c in catalogue}
    context = session['context']
    common = [float(session['features'][k]) for k in NUMERIC]
    common += [float(context[k]) for k in ('asset_criticality', 'current_likelihood', 'impact')]
    groups = set(asset.get('control_groups', []))
    matrix = []
    for cid in labels:
        control = by_id[cid]
        control_techniques = control.get('mitigates_attack_techniques', [])
        exact = sum(t in control_techniques for t in set(techniques))
        parent = sum(any(technique_match(t, ct) for ct in control_techniques) for t in set(techniques))
        applies = set(control.get('applies_to', []))
        matrix.append(common + [all_members[cid], matched_members[cid],
            event_members[cid] / len(alerts), exact, parent,
            int(bool(applies & groups) or 'all' in applies), len(set(techniques)), len(matched_risks)])
    array = np.asarray(matrix, dtype=np.float32)
    if not np.isfinite(array).all() or array.shape != (len(labels), len(PAIR_FEATURES)):
        raise ValueError('Invalid grounded candidate feature matrix')
    return labels, array, sorted(cid for cid in labels if matched_members[cid])


class GroundedControlRecommender:
    """Read-only experimental relevance service; never executes mitigation."""
    def __init__(self, artifact):
        if artifact.get('schema') != SCHEMA or artifact.get('features') != PAIR_FEATURES:
            raise ValueError('Grounded control feature schema mismatch')
        if artifact.get('sklearn_version') != sklearn.__version__:
            raise ValueError('Use the pinned scikit-learn environment')
        self.artifact = artifact

    @classmethod
    def load(cls, path):
        """Load trusted local training output after checking its sidecar digest."""
        path = Path(path)
        metadata = json.loads(path.with_suffix('.json').read_text())
        if hashlib.sha256(path.read_bytes()).hexdigest() != metadata['model_sha256']:
            raise ValueError('Grounded control artifact checksum mismatch')
        return cls(joblib.load(path))

    def recommend(self, session, alerts, asset, registered_risks, catalogue):
        if session.get('data_provenance') != 'synthetic':
            raise ValueError('This repair is validated for synthetic replay only; real-data release is blocked')
        if catalogue_digest(catalogue) != self.artifact['catalogue_sha256']:
            raise ValueError('Control catalogue changed since training')
        labels, matrix, policy = candidate_features(session, alerts, asset, registered_risks, catalogue)
        if not any(a.get('mitre_technique') for a in alerts):
            return {'recommendations': [], 'catalogue_policy_candidates': [],
                    'source': 'not_run', 'reason': 'Observed technique context is missing; analyst review required',
                    'release_eligible': False, 'automatic_execution': False}
        scores = self.artifact['classifier'].predict_proba(matrix)[:, 1]
        controls = {c['control_id']: c for c in catalogue}
        learned = []
        for cid, score, candidate_row in zip(labels, scores, matrix):
            if score < self.artifact['threshold']:
                continue
            # These inputs contain associations, not trustworthy control-state
            # assessments. Do not claim "missing", "implemented" or "install".
            learned.append({'control_id': cid, 'name': controls[cid]['name'],
                            'model_score': float(score), 'current_state': 'unknown',
                            'action_type': 'review', 'requires_human_approval': True,
                            'positive_fit_support': self.artifact['positive_fit_support'].get(cid, 0),
                            'matched_registered_risks': int(candidate_row[PAIR_FEATURES.index('candidate_matched_risk_count')]),
                            'reason': ('Registered-risk control link matches observed technique context'
                                       if cid in policy else 'Model-selected candidate without a matching registered-risk link; analyst review required'),
                            'evidence_status': ('synthetic_training_support' if self.artifact['positive_fit_support'].get(cid, 0) >= 20
                                                else 'sparse_or_unseen_label_review_required'),
                            'source': 'experimental_grounded_candidate_model'})
        learned.sort(key=lambda x: (-x['model_score'], x['control_id']))
        return {'recommendations': learned, 'catalogue_policy_candidates': policy,
                'source': 'experimental_grounded_candidate_model',
                'independent_expert_validation': False, 'release_eligible': False,
                'automatic_execution': False,
                'validation_scope': 'Synthetic association matching; no demonstrated ML advantage over catalogue rules',
                'score_meaning': 'Uncalibrated synthetic association relevance, not efficacy or risk reduction'}
